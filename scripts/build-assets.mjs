// Compiles the viewer's template, stylesheet and browser script into string
// constants, with the hashes the Content-Security-Policy and the library tags
// need (SPEC §3.3, §5.3, §6). Nothing is read at run time.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => readFileSync(root + path, "utf8").replace(/\r\n?/g, "\n");
const digest = (algorithm, data) => createHash(algorithm).update(data).digest("base64");

const pkg = JSON.parse(read("package.json"));

// The CDN serves a package's files as published, so the hash of the file in
// node_modules is the hash of the file a viewer will load.
function library(name, file) {
  const version = pkg.devDependencies[name];
  if (!/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`${name} must be pinned to an exact version, found "${version}"`);
  }
  const bytes = readFileSync(`${root}node_modules/${name}/${file}`);
  return {
    url: `https://cdn.jsdelivr.net/npm/${name}@${version}/${file}`,
    sri: `sha384-${digest("sha384", bytes)}`,
  };
}

async function script(define) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/viewer/main.ts"],
    bundle: true,
    format: "iife",
    target: "es2020",
    minify: false,
    sourcemap: false,
    legalComments: "inline",
    charset: "ascii",
    define,
    write: false,
    logLevel: "warning",
  });
  return result.outputFiles[0].text.replace(/\r\n?/g, "\n");
}

// Text inlined into a <script> or <style> element must not be able to end it.
function inlineable(text, element) {
  if (new RegExp(`</${element}|<!--`, "i").test(text)) {
    throw new Error(`The viewer's ${element} contains "</${element}" or "<!--"`);
  }
  return text;
}

// In the source template each placeholder is written so that the file is
// valid HTML with valid CSS, JSON and JavaScript inside it, and a formatter
// may lay it out as it likes: the stylesheet and script are comments, the data
// a string. Here each becomes the bare placeholder, with nothing else inside
// its element, because the policy's hashes are of the inlined text alone.
function tighten(source) {
  const forms = [
    [/(<style[^>]*>)\s*\/\*\{\{CSS\}\}\*\/\s*(<\/style>)/, "$1{{CSS}}$2"],
    [/(<script type="application\/json"[^>]*>)\s*"\{\{DATA\}\}"\s*(<\/script>)/, "$1{{DATA}}$2"],
    [/(<script>)\s*\/\*\{\{JS\}\}\*\/\s*(<\/script>)/, "$1{{JS}}$2"],
    // Where the libraries go: two elements that load them, or that hold them.
    [/<!--\s*\{\{LIBRARIES\}\}\s*-->/, "{{LIBRARIES}}"],
  ];
  let text = source;
  for (const [pattern, replacement] of forms) {
    if (!pattern.test(text)) throw new Error(`The template has nothing matching ${pattern}`);
    text = text.replace(pattern, replacement);
  }
  // A note to the linter is for whoever edits the template, not for readers
  // of a generated viewer.
  return text.replace(/^[ \t]*<!--\s*biome-ignore\b[\s\S]*?-->[ \t]*\n/gm, "");
}

const template = tighten(read("src/viewer/viz.html"));
const css = inlineable(read("src/viewer/viz.css"), "style");
const js = inlineable(await script({ __OKF_SANITIZE__: "true" }), "script");

const constants = {
  VERSION: pkg.version,
  TEMPLATE: template,
  CSS: css,
  JS: js,
  CSS_SHA256: digest("sha256", css),
  JS_SHA256: digest("sha256", js),
  LIBS: {
    cytoscape: library("cytoscape", "dist/cytoscape.min.js"),
    marked: library("marked", "marked.min.js"),
  },
};

const lines = ["// Generated by scripts/build-assets.mjs. Do not edit.", ""];
for (const [name, value] of Object.entries(constants)) {
  const literal = JSON.stringify(value, null, 2);
  lines.push(`export const ${name} = ${literal}${typeof value === "string" ? "" : " as const"};`);
}

mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(`${root}src/generated/assets.ts`, `${lines.join("\n")}\n`);

// The libraries themselves, for a viewer that carries them and loads nothing
// (SPEC §5.3). They are a module of their own, reached only through the
// package's `inline` entry, so that a caller who loads them from the CDN
// doesn't carry 400 kB of them. Each is the file npm published, licence notice
// included, with the hash the Content-Security-Policy names it by.
function inlineLibrary(name, file) {
  const code = readFileSync(`${root}node_modules/${name}/${file}`, "utf8");
  // Inside a script element, "</script" ends it, "<!--" then "<script" would
  // hide the tag that ends it, and the parser rewrites a carriage return, so
  // the text would no longer match its hash.
  if (/<\/script/i.test(code) || (code.includes("<!--") && /<script/i.test(code))) {
    throw new Error(`${name} can't be written inside a script element`);
  }
  if (code.includes("\r")) throw new Error(`${name} contains a carriage return`);
  return { code, sha256: digest("sha256", code) };
}

const inline = {
  cytoscape: inlineLibrary("cytoscape", "dist/cytoscape.min.js"),
  marked: inlineLibrary("marked", "marked.min.js"),
};
writeFileSync(
  `${root}src/generated/libraries.ts`,
  [
    "// Generated by scripts/build-assets.mjs. Do not edit.",
    "",
    `export const INLINE_LIBRARIES = ${JSON.stringify(inline, null, 2)};`,
    "",
  ].join("\n"),
);

// For test T5 only: the same viewer with the sanitizing steps switched off,
// to show that the Content-Security-Policy alone stops injected script.
// Nothing under src/ imports this file, so it is in no build of the package.
const unsafeJs = inlineable(await script({ __OKF_SANITIZE__: "false" }), "script");
const unsafe = { ...constants, JS: unsafeJs, JS_SHA256: digest("sha256", unsafeJs) };
writeFileSync(
  `${root}src/generated/assets.unsafe.ts`,
  [
    "// Generated by scripts/build-assets.mjs. Do not edit. For tests only.",
    "",
    `export const UNSAFE_ASSETS = ${JSON.stringify(unsafe, null, 2)};`,
    "",
  ].join("\n"),
);
